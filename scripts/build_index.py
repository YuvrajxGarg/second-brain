#!/usr/bin/env python3
"""Regenerate INDEX.md and TAGS.md from entry frontmatter. No dependencies."""
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIRS = [ROOT / "topics", ROOT / "inbox"]


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.split(" #")[0].strip()
    tags = meta.get("tags", "").strip("[]")
    meta["tags"] = [t.strip().strip("'\"") for t in tags.split(",") if t.strip()]
    meta.setdefault("title", path.stem)
    meta.setdefault("added", "")
    meta["path"] = path.relative_to(ROOT).as_posix()
    return meta


def main():
    entries = [parse(p) for d in DIRS if d.exists() for p in d.rglob("*.md")]
    entries.sort(key=lambda e: (e["added"], e["title"]), reverse=True)

    by_topic = defaultdict(list)
    by_tag = defaultdict(list)
    for e in entries:
        group = "inbox" if e["path"].startswith("inbox/") else e["path"].split("/")[1]
        by_topic[group].append(e)
        for t in e["tags"]:
            by_tag[t].append(e)

    def line(e):
        bits = [f"[{e['title']}]({e['path']})"]
        if e.get("type"):
            bits.append(f"`{e['type']}`")
        if e["added"]:
            bits.append(e["added"])
        if e["tags"]:
            bits.append(" ".join(f"#{t}" for t in e["tags"]))
        return "- " + " · ".join(bits)

    out = ["# Index", "", f"_{len(entries)} entries. Generated by `scripts/build_index.py`; do not edit by hand._", ""]
    for topic in sorted(by_topic):
        out += [f"## {topic} ({len(by_topic[topic])})", ""] + [line(e) for e in by_topic[topic]] + [""]
    (ROOT / "INDEX.md").write_text("\n".join(out), encoding="utf-8")

    out = ["# Tags", "", f"_{len(by_tag)} tags. Generated by `scripts/build_index.py`; do not edit by hand._", ""]
    for tag in sorted(by_tag):
        out += [f"## #{tag} ({len(by_tag[tag])})", ""] + [line(e) for e in by_tag[tag]] + [""]
    (ROOT / "TAGS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"Indexed {len(entries)} entries, {len(by_tag)} tags.")


if __name__ == "__main__":
    main()
